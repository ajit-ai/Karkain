# Generates src/compiler/sqlite_runtime.kark from runtime/sqlite/c/karkain_sqlite.*
# The vendored SQLite amalgamation is NOT embedded here; the Go CLI compiles
# c/vendor/sqlite3.c separately when a program uses sqlite_* builtins.

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$srcDir = Join-Path $root "runtime/sqlite/c"
$outPath = Join-Path $root "src/compiler/sqlite_runtime.kark"

$files = @("karkain_sqlite.h", "karkain_sqlite.c")

function Escape-KarkString([string]$s) {
    return $s.Replace("\", "\\").Replace('"', '\"')
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Generated by scripts/gen-sqlite-runtime.ps1 - DO NOT EDIT BY HAND.")
[void]$sb.AppendLine("// v1.2.22: minimal SQLite binding embedded for the self-hosted backend.")
$digests = @()
foreach ($f in $files) {
    $bytes = [System.IO.File]::ReadAllBytes((Join-Path $srcDir $f))
    $norm = $bytes | Where-Object { $_ -ne 13 }
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $hex = ($sha.ComputeHash($norm) | ForEach-Object { $_.ToString("x2") }) -join ""
    $digests += "$f=$hex"
}
[void]$sb.AppendLine("// runtime-sha256: " + ($digests -join " "))
[void]$sb.AppendLine("")
[void]$sb.AppendLine("// emitSQLiteRuntime appends the C23 SQLite binding.")
[void]$sb.AppendLine("func emitSQLiteRuntime(state) {")

foreach ($f in $files) {
    [void]$sb.AppendLine('    emitLine(state, "// ==== v1.2.22 runtime source: ' + $f + ' ====")')
    $text = [System.IO.File]::ReadAllText((Join-Path $srcDir $f), [System.Text.Encoding]::UTF8)
    foreach ($line in $text -split '\r?\n') {
        $t = $line.Trim()
        if ($t.StartsWith('#include "karkain_sqlite.h"')) { continue }
        [void]$sb.AppendLine('    emitLine(state, "' + (Escape-KarkString $line) + '")')
    }
}
[void]$sb.AppendLine("}")

$final = $sb.ToString() -replace '\r(?=\n)', ''
[System.IO.File]::WriteAllText($outPath, $final, (New-Object System.Text.UTF8Encoding $false))
Write-Host "wrote $outPath"
