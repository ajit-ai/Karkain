# Generates src/compiler/rc_runtime.kark from runtime/rc/c/*.
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$srcDir = Join-Path $root "runtime/rc/c"
$outPath = Join-Path $root "src/compiler/rc_runtime.kark"

$files = @("karkain_rc.h", "karkain_rc.c")

function Escape-KarkString([string]$s) {
    return $s.Replace("\", "\\").Replace('"', '\"')
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Generated by scripts/gen-rc-runtime.ps1 - DO NOT EDIT BY HAND.")
[void]$sb.AppendLine("// v1.2.24: C23 reference-counting runtime embedded for the self-hosted backend.")
$digests = @()
foreach ($f in $files) {
    $bytes = [System.IO.File]::ReadAllBytes((Join-Path $srcDir $f))
    $norm = $bytes | Where-Object { $_ -ne 13 }
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $hex = ($sha.ComputeHash($norm) | ForEach-Object { $_.ToString("x2") }) -join ""
    $digests += "$f=$hex"
}
[void]$sb.AppendLine("// runtime-sha256: " + ($digests -join " "))
[void]$sb.AppendLine("")
[void]$sb.AppendLine("// emitRCRuntime appends the C23 RC runtime (header + implementation, self-include stripped).")
[void]$sb.AppendLine("func emitRCRuntime(state) {")

foreach ($f in $files) {
    [void]$sb.AppendLine('    emitLine(state, "// ==== v1.2.24 runtime source: ' + $f + ' ====")')
    $text = [System.IO.File]::ReadAllText((Join-Path $srcDir $f), [System.Text.Encoding]::UTF8)
    foreach ($line in $text -split '\r?\n') {
        $t = $line.Trim()
        if ($t.StartsWith('#include "karkain_rc.h"')) { continue }
        [void]$sb.AppendLine('    emitLine(state, "' + (Escape-KarkString $line) + '")')
    }
}
[void]$sb.AppendLine("}")

$final = $sb.ToString() -replace '\r(?=\n)', ''
[System.IO.File]::WriteAllText($outPath, $final, (New-Object System.Text.UTF8Encoding $false))
Write-Host "wrote $outPath"